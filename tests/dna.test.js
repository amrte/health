import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createParser, readGenomeFile } from '../js/genome.js';
import { readSnp, PANELS, WANTED, BY_POSITION } from '../js/dna-variants.js';
import { dnaLabFindings } from '../js/dna-eval.js';

const ME = `# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2024
# We are using reference human assembly build 37 (also known as Annotation Release 104).
# rsid\tchromosome\tposition\tgenotype
rs548049170\t1\t69869\tTT
rs6025\t1\t169519049\tCT
i3002432\t11\t46761055\tGA
rs1800562\t6\t26093141\tAA
rs1799945\t6\t26091179\tCC
rs4149056\t12\t21331549\t--
rs429358\t19\t45411941\tCT
rs7412\t19\t45412079\tCT
rs1815739\t11\t66328095\tT
`;
const TMG = `rsid\tChromosome\tposition\tgenotype
1:169519049\t1\t169519049\tCC
rs1800562\t6\t26093141\tGA
rs4149056\t12\t21331549\tTC
GSA-rs4988235\t2\t136608646\tAA
`;

function parse(text) {
  const p = createParser(WANTED, BY_POSITION);
  p.push(text.slice(0, 50)); // chunk boundaries in the middle of lines
  p.push(text.slice(50));
  return p.end();
}

test('23andMe raw file', () => {
  const r = parse(ME);
  assert.equal(r.provider, '23andMe');
  assert.equal(r.build, 'GRCh37');
  assert.equal(r.total, 9);
  assert.equal(r.snps.rs1799963, 'GA', 'internal id matched by position');
  assert.equal(r.snps.rs4149056, undefined, 'no-call dropped');
  assert.equal(r.snps.rs1815739, 'T', 'single-letter call kept');
});

test('tellmeGen raw file (no comment block, position ids, comma variant)', () => {
  const r = parse(TMG);
  assert.equal(r.snps.rs6025, 'CC');
  assert.equal(r.snps.rs4988235, 'AA');
  assert.equal(r.snps.rs1800562, 'GA');
  const csv = parse('rsid,Chromosome,position,genotype\n"rs1800562","6","26093141","AG"\n');
  assert.equal(csv.snps.rs1800562, 'AG');
});

test('alleles on the plus strand, including reference = variant cases', () => {
  assert.equal(readSnp('rs6025', 'CC').count, 0, 'F5: C is normal');
  assert.equal(readSnp('rs6025', 'CT').count, 1);
  assert.equal(readSnp('rs6025', 'TT').count, 2, 'F5: T (the GRCh37 reference) is Leiden');
  assert.equal(readSnp('rs1815739', 'TT').count, 2, 'ACTN3: T (reference) is 577X');
  const flipped = readSnp('rs1800562', 'TC'); // C282Y on the minus strand
  assert.deepEqual([flipped.gt, flipped.count, flipped.flipped], ['AG', 1, true]);
  assert.equal(readSnp('rs1799945', 'AT').unexpected, true, 'H63D is C/G: a flip cannot be detected');
  assert.equal(readSnp('rs1800562', 'ID'), null);
});

test('interpretations', () => {
  const geno = (snps) => (rs) => readSnp(rs, snps[rs]);
  const run = (id, snps) => PANELS.find((p) => p.id === id).interpret(geno(snps));
  assert.equal(run('hfe', { rs1800562: 'AA', rs1799945: 'CC' }).summary, 'Two copies of C282Y');
  assert.equal(run('hfe', { rs1800562: 'AG', rs1799945: 'CG' }).summary, 'C282Y and H63D, one copy each');
  assert.equal(run('hfe', {}), null, 'not tested');
  assert.equal(run('clot', { rs6025: 'CT', rs1799963: 'GG' }).level, 'attention');
  assert.equal(run('clot', { rs6025: 'CT', rs1799963: 'GA' }).level, 'alert');
  assert.equal(run('clot', { rs6025: 'CC', rs1799963: 'GG' }).level, 'good');
  assert.equal(run('statin', { rs4149056: 'TC' }).summary, 'Decreased function (TC)');
  assert.equal(run('cyp2c19', { rs4244285: 'GA', rs4986893: 'GG', rs12248560: 'CT' }).summary, 'Intermediate metabolizer', '*2/*17');
  assert.equal(run('cyp2c19', { rs4244285: 'GG', rs4986893: 'GG', rs12248560: 'TT' }).summary, 'Ultrarapid metabolizer');
  assert.equal(run('lct', { rs4988235: 'GG' }).summary, 'Likely lactase non-persistent');
  assert.equal(run('apoe', { rs429358: 'TT', rs7412: 'CC' }).summary, 'ε3/ε3');
  assert.equal(run('apoe', { rs429358: 'CT', rs7412: 'CC' }).summary, 'ε3/ε4');
  assert.equal(run('apoe', { rs429358: 'CT', rs7412: 'CT' }).summary, 'ε2/ε4');
  assert.equal(run('apoe', { rs429358: 'TT', rs7412: 'TT' }).summary, 'ε2/ε2');
});

test('DNA combined with lab values', () => {
  const by = new Map([['ferritin', { pts: [{ v: 420, status: 'high' }] }], ['ldl', { pts: [{ v: 3.4 }] }]]);
  const f = dnaLabFindings([{ provider: 'x', snps: { rs1800562: 'AA', rs4149056: 'TC' } }], by, { sex: 'male' });
  assert.equal(f[0].title, 'HFE genotype with raised iron values');
  assert.equal(f[0].level, 'alert');
  assert.match(f[1].title, /SLCO1B1 decreased function/);
});

test('ZIP from the provider', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'dna-'));
  writeFileSync(join(dir, 'genome_Test_v5_Full_20240101.txt'), ME);
  execFileSync('zip', ['-q', join(dir, 'genome.zip'), 'genome_Test_v5_Full_20240101.txt'], { cwd: dir });
  const file = Object.assign(new Blob([readFileSync(join(dir, 'genome.zip'))]), { name: 'genome_Test.zip' });
  const r = await readGenomeFile(file, WANTED, BY_POSITION);
  assert.equal(r.provider, '23andMe');
  assert.equal(r.fileName, 'genome_Test_v5_Full_20240101.txt');
  assert.equal(r.snps.rs1800562, 'AA');
  await assert.rejects(readGenomeFile(Object.assign(new Blob(['hello\nworld']), { name: 'x.txt' }), WANTED, BY_POSITION), /raw DNA/);
});
