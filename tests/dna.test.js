function parse(text) {
  const p = createParser(WANTED, BY_POSITION);
  p.push(text.slice(0, 50)); // chunk boundaries in the middle of lines
  p.push(text.slice(50));
  return p.end();
}

test('23andMe raw file', () => {
  const r = parse(ME);
  assert.equal(r.provider, '23andMe');
  assert.equal(r.build, 'GRCh37');
  assert.equal(r.total, 9);
  assert.equal(r.snps.rs1799963, 'GA', 'internal id matched by position');
  assert.equal(r.snps.rs4149056, undefined, 'no-call dropped');
  assert.equal(r.snps.rs1815739, 'T', 'single-letter call kept');
});

test('tellmeGen raw file (no comment block, position ids, comma variant)', () => {
  const r = parse(TMG);
  assert.equal(r.snps.rs6025, 'CC');
  assert.equal(r.snps.rs4988235, 'AA');
  assert.equal(r.snps.rs1800562, 'GA');
  const csv = parse('rsid,Chromosome,position,genotype\n"rs1800562","6","26093141","AG"\n');
  assert.equal(csv.snps.rs1800562, 'AG');
});

test('alleles on the plus strand, including reference = variant cases', () => {
  assert.equal(readSnp('rs6025', 'CC').count, 0, 'F5: C is normal');
  assert.equal(readSnp('rs6025', 'CT').count, 1);
  assert.equal(readSnp('rs6025', 'TT').count, 2, 'F5: T (the GRCh37 reference) is Leiden');
  assert.equal(readSnp('rs1815739', 'TT').count, 2, 'ACTN3: T (reference) is 577X');
  const flipped = readSnp('rs1800562', 'TC'); // C282Y on the minus strand
  assert.deepEqual([flipped.gt, flipped.count, flipped.flipped], ['AG', 1, true]);
  assert.equal(readSnp('rs1799945', 'AT').unexpected, true, 'H63D is C/G: a flip cannot be detected');
  assert.equal(readSnp('rs1800562', 'ID'), null);
});

test('interpretations', () => {
  const geno = (snps) => (rs) => readSnp(rs, snps[rs]);
  const run = (id, snps) => PANELS.find((p) => p.id === id).interpret(geno(snps));
  assert.equal(run('hfe', { rs1800562: 'AA', rs1799945: 'CC' }).summary, 'Two copies of C282Y');
  assert.equal(run('hfe', { rs1800562: 'AG', rs1799945: 'CG' }).summary, 'C282Y and H63D, one copy each');
  assert.equal(run('hfe', {}), null, 'not tested');
  assert.equal(run('clot', { rs6025: 'CT', rs1799963: 'GG' }).level, 'attention');
  assert.equal(run('clot', { rs6025: 'CT', rs1799963: 'GA' }).level, 'alert');
  assert.equal(run('clot', { rs6025: 'CC', rs1799963: 'GG' }).level, 'good');
  assert.equal(run('statin', { rs4149056: 'TC' }).summary, 'Decreased function (TC)');
  assert.equal(run('cyp2c19', { rs4244285: 'GA', rs4986893: 'GG', rs12248560: 'CT' }).summary, 'Intermediate metabolizer', '*2/*17');
  assert.equal(run('cyp2c19', { rs4244285: 'GG', rs4986893: 'GG', rs12248560: 'TT' }).summary, 'Ultrarapid metabolizer');
  assert.equal(run('lct', { rs4988235: 'GG' }).summary, 'Likely lactase non-persistent');
  assert.equal(run('apoe', { rs429358: 'TT', rs7412: 'CC' }).summary, 'ε3/ε3');
  assert.equal(run('apoe', { rs429358: 'CT', rs7412: 'CC' }).summary, 'ε3/ε4');
  assert.equal(run('apoe', { rs429358: 'CT', rs7412: 'CT' }).summary, 'ε2/ε4');
  assert.equal(run('apoe', { rs429358: 'TT', rs7412: 'TT' }).summary, 'ε2/ε2');
});

test('DNA combined with lab values', () => {
  const by = new Map([['ferritin', { pts: [{ v: 420, status: 'high' }] }], ['ldl', { pts: [{ v: 3.4 }] }]]);
  const f = dnaLabFindings([{ provider: 'x', snps: { rs1800562: 'AA', rs4149056: 'TC' } }], by, { sex: 'male' });
  assert.equal(f[0].title, 'HFE genotype with raised iron values');
  assert.equal(f[0].level, 'alert');
  assert.match(f[1].title, /SLCO1B1 decreased function/);
});

test('ZIP from the provider', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'dna-'));
  writeFileSync(join(dir, 'genome_Test_v5_Full_20240101.txt'), ME);
  execFileSync('zip', ['-q', join(dir, 'genome.zip'), 'genome_Test_v5_Full_20240101.txt'], { cwd: dir });
  const file = Object.assign(new Blob([readFileSync(join(dir, 'genome.zip'))]), { name: 'genome_Test.zip' });
  const r = await readGenomeFile(file, WANTED, BY_POSITION);
  assert.equal(r.provider, '23andMe');
  assert.equal(r.fileName, 'genome_Test_v5_Full_20240101.txt');
  assert.equal(r.snps.rs1800562, 'AA');
  await assert.rejects(readGenomeFile(Object.assign(new Blob(['hello\nworld']), { name: 'x.txt' }), WANTED, BY_POSITION), /raw DNA/);
});

// ---- VCF from genome sequencing ------------------------------------------------------

const VCF_HEAD = (build) => `##fileformat=VCFv4.2
##source=DRAGEN
##contig=<ID=chr1,length=${build === 38 ? 248956422 : 249250621}>
##reference=file:///ref/${build === 38 ? 'hg38' : 'hg19'}.fa
#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE01
`;
const rec = (chrom, pos, ref, alt, gt, { id = '.', filter = 'PASS', info = '.' } = {}) => `${chrom}\t${pos}\t${id}\t${ref}\t${alt}\t50\t${filter}\t${info}\tGT:DP\t${gt}:30\n`;
const vcf = (text, name = 'sample.vcf') => readGenomeFile(Object.assign(new Blob([text]), { name }), WANTED, BY_POSITION, SNPS);

test('VCF (GRCh38, variant-only, no rsIDs): genotypes from REF/ALT by position', async () => {
  const r = await vcf(VCF_HEAD(38)
    + rec('chr1', 11796321, 'G', 'A', '0/1')
    + rec('chr1', 169549811, 'C', 'T', '0|1')
    + rec('chr6', 26092913, 'G', 'A', '1/1')
    + rec('chr10', 94761900, 'C', 'T,G', '1/2') // multi-allelic: one allele isn't ours
    + rec('chr19', 44908684, 'T', 'C', './.')
    + rec('chr11', 46739505, 'G', 'A', '0/1', { filter: 'LowQual' }));
  assert.equal(r.format, 'VCF');
  assert.equal(r.build, 'GRCh38');
  assert.equal(r.total, 6);
  assert.deepEqual(r.snps, { rs1801133: 'GA', rs6025: 'CT', rs1800562: 'AA' });
  assert.deepEqual(r.inferred, [], 'not a whole genome: nothing taken as reference');
  assert.equal(r.provider, 'VCF file');
  assert.equal(readSnp('rs6025', r.snps.rs6025).count, 1);
});

test('VCF (GRCh37 with rsIDs and reference calls, as converted chip data)', async () => {
  const r = await vcf(VCF_HEAD(37)
    + rec('1', 169519049, 'T', 'C', '1/1', { id: 'rs6025' }) // GRCh37 reference T is Leiden: 1/1 = CC = normal
    + rec('11', 66328095, 'T', 'C', '0/1', { id: 'rs1815739' })
    + rec('19', 45412079, 'C', '.', '0/0', { id: 'rs7412' })
    + rec('6', 99, 'G', 'A', '0/1', { id: 'rs1800562' }), // rsID matches even at another position
  'dante_labs_snp.vcf');
  assert.equal(r.build, 'GRCh37');
  assert.equal(r.provider, 'Dante Labs');
  assert.deepEqual(r.snps, { rs6025: 'CC', rs1815739: 'TC', rs7412: 'CC', rs1800562: 'GA' });
  assert.equal(readSnp('rs6025', 'CC').count, 0);
});

test('gVCF reference blocks give the reference genotype at covered sites', async () => {
  const r = await vcf(VCF_HEAD(37)
    + rec('1', 169519000, 'A', '<NON_REF>', '0/0', { info: 'END=169519100' }) // covers rs6025: reference T/T on GRCh37
    + rec('2', 136608000, 'C', '<NON_REF>', '0/0', { info: 'END=136608600' }) // ends before rs4988235
    + rec('6', 26093000, 'A', '<*>', '0/0', { info: 'END=26093200' }));
  assert.equal(r.snps.rs6025, 'TT', 'a real reference call, also where the reference is the variant');
  assert.equal(r.snps.rs1800562, 'GG');
  assert.equal(r.snps.rs4988235, undefined);
  assert.deepEqual(r.inferred, []);
});

test('whole-genome VCF: unlisted sites are the reference, only where that is the normal allele', async () => {
  const filler = (n) => {
    const parts = [];
    for (let i = 0; i < n; i++) parts.push(`chr3\t${1000 + i}\t.\tA\tG\t50\tPASS\t.\tGT\t0/1\n`);
    return parts.join('');
  };
  const big = filler(1000000);
  const r38 = await vcf(VCF_HEAD(38)
    + rec('chr6', 26092913, 'G', 'A', '0/1')
    + rec('chr11', 46739505, 'G', 'A', '0/1', { filter: 'LowQual' }) // listed but filtered: not assumed
    + rec('chr12', 21178610, 'TTTTTAG', 'T', '0/1') // deletion spanning rs4149056: not assumed
    + big);
  assert.equal(r38.wholeGenome, true);
  assert.equal(r38.provider, 'Whole genome (VCF)');
  assert.equal(r38.snps.rs1800562, 'GA');
  assert.equal(r38.snps.rs6025, 'CC', 'GRCh38 reference is the normal allele');
  assert.equal(r38.snps.rs1799963, undefined);
  assert.equal(r38.snps.rs4149056, undefined);
  assert.ok(r38.inferred.includes('rs6025') && !r38.inferred.includes('rs1800562'));
  assert.equal(r38.inferred.length, Object.keys(SNPS).length - 3);

  const r37 = await vcf(VCF_HEAD(37) + big);
  assert.equal(r37.snps.rs6025, undefined, 'GRCh37 reference is Leiden: never assumed from a missing line');
  assert.equal(r37.snps.rs1815739, undefined);
  assert.equal(r37.snps.rs1801133, 'GG');
});

// bgzip: gzip members with a BC extra field giving the block size.
function bgzf(text) {
  const blocks = [];
  const data = Buffer.from(text);
  for (let i = 0; i <= data.length; i += 60000) {
    const part = data.subarray(i, i + 60000);
    const cdata = zlib.deflateRawSync(part);
    const head = Buffer.from([0x1f, 0x8b, 8, 4, 0, 0, 0, 0, 0, 0xff, 6, 0, 66, 67, 2, 0, 0, 0]);
    head.writeUInt16LE(head.length + cdata.length + 8 - 1, 16);
    const tail = Buffer.alloc(8);
    tail.writeUInt32LE(zlib.crc32(part), 0);
    tail.writeUInt32LE(part.length, 4);
    blocks.push(head, cdata, tail);
  }
  return Buffer.concat(blocks);
}

test('compressed VCF: bgzip (.vcf.gz), plain gzip, and inside a ZIP', async () => {
  const lines = [];
  for (let i = 0; i < 20000; i++) lines.push(rec('chr3', 1000 + i, 'A', 'G', '0/1').trimEnd());
  const text = VCF_HEAD(38) + lines.join('\n') + '\n' + rec('chr1', 11796321, 'G', 'A', '1/1') + 'chr1\t11796400\t.\tC\tT\t50\tPASS\tNOTE=Ünïcödé\tGT\t0/1\n';
  const gz = bgzf(text);
  assert.ok(gz.indexOf(Buffer.from([0x1f, 0x8b, 8, 4]), 100) > 0, 'several blocks');
  let progress = 0;
  const r = await readGenomeFile(Object.assign(new Blob([gz]), { name: 'nebula.vcf.gz' }), WANTED, BY_POSITION, SNPS, (f) => { progress = f; });
  assert.equal(r.snps.rs1801133, 'AA');
  assert.equal(r.total, 20002);
  assert.equal(r.provider, 'Nebula Genomics');
  assert.ok(progress > 0.9);
  const plain = await readGenomeFile(Object.assign(new Blob([zlib.gzipSync(text)]), { name: 'x.vcf.gz' }), WANTED, BY_POSITION, SNPS);
  assert.equal(plain.snps.rs1801133, 'AA');
  const dir = mkdtempSync(join(tmpdir(), 'vcf-'));
  writeFileSync(join(dir, 'genome.vcf.gz'), gz);
  execFileSync('zip', ['-q', join(dir, 'g.zip'), 'genome.vcf.gz'], { cwd: dir });
  const zipped = await readGenomeFile(Object.assign(new Blob([readFileSync(join(dir, 'g.zip'))]), { name: 'g.zip' }), WANTED, BY_POSITION, SNPS);
  assert.equal(zipped.snps.rs1801133, 'AA');
  assert.equal(zipped.fileName, 'genome.vcf.gz');
  await assert.rejects(vcf('##fileformat=VCFv4.2\n#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\nchr1\t5\t.\tA\tG\t.\t.\t.\n'), /no genotype column/);
});
